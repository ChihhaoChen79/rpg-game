// Tuning sheets command line. See tuning/README.md.
//   npm run tuning                  CSV -> data/*.json, strings, map spawn numbers, tuning/CATALOG.md
//   npm run tuning:export           data/*.json -> CSV (overwrites the sheets; for first setup or recovery)
//   npm run tuning:exp -- 50 1.5    rewrite tuning/exp.csv as base x growth^(level-1)
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { buildCatalog } from './catalog.mjs';
import { exponentialExp, exportSheets, importSheets, SHEETS } from './tuning-lib.mjs';

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const mapIds = () => readdirSync('maps').filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5));
const loadMaps = () => Object.fromEntries(mapIds().map((id) => [id, readJson(`maps/${id}.json`)]));

/** One JSON entry per line: readable diffs, still valid JSON. */
function writeTable(path, table) {
  const lines = Object.entries(table).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  writeFileSync(path, `{\n${lines.join(',\n')}\n}\n`);
}

/** Update (or add) keys in the strings file without reformatting the rest of it. */
function updateStrings(names) {
  const path = 'data/strings.zh-TW.json';
  let text = readFileSync(path, 'utf8');
  for (const [key, value] of Object.entries(names)) {
    const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(`("${esc}": )"(?:[^"\\\\]|\\\\.)*"`);
    if (re.test(text)) text = text.replace(re, (_m, head) => `${head}${JSON.stringify(value)}`);
    else {
      // Insert after the last key with the same prefix ("item." or "monster.").
      const prefix = key.slice(0, key.indexOf('.') + 1);
      const all = [...text.matchAll(new RegExp(`\\n  "${prefix.replace('.', '\\.')}[^"]*": "(?:[^"\\\\]|\\\\.)*",`, 'g'))];
      const last = all[all.length - 1];
      if (!last) throw new Error(`Can't place new string ${key}`);
      const at = last.index + last[0].length;
      text = `${text.slice(0, at)}\n  ${JSON.stringify(key)}: ${JSON.stringify(value)},${text.slice(at)}`;
    }
  }
  JSON.parse(text); // still valid?
  writeFileSync(path, text);
}

function readSheets() {
  const csv = {};
  for (const name of Object.keys(SHEETS)) csv[name] = readFileSync(`tuning/${name}.csv`, 'utf8');
  return csv;
}

const cmd = process.argv[2] ?? 'import';

if (cmd === 'export') {
  mkdirSync('tuning', { recursive: true });
  const sheets = exportSheets({
    items: readJson('data/items.json'), monsters: readJson('data/monsters.json'),
    totalExp: readJson('data/exp-table.json').totalExp, strings: readJson('data/strings.zh-TW.json'), maps: loadMaps(),
  });
  for (const [name, text] of Object.entries(sheets)) writeFileSync(`tuning/${name}.csv`, text);
  console.log('Wrote tuning/*.csv from data/. Edit them, then run: npm run tuning');
} else if (cmd === 'exp') {
  const base = Number(process.argv[3] ?? 50);
  const growth = Number(process.argv[4] ?? 1.5);
  const cap = readJson('data/balance.json').levelCap;
  writeFileSync('tuning/exp.csv', exponentialExp(cap, base, growth));
  console.log(`Wrote tuning/exp.csv: Exp to next level = ${base} x ${growth}^(level-1), levels 1-${cap}. Now run: npm run tuning`);
} else if (cmd === 'import') {
  const maps = loadMaps();
  const r = importSheets(readSheets(), { maps, exists: existsSync });
  if (r.errors.length) {
    console.error(`Found ${r.errors.length} problem(s); nothing was changed:\n  ${r.errors.join('\n  ')}`);
    process.exit(1);
  }
  const cap = readJson('data/balance.json').levelCap;
  if (r.totalExp.length !== cap) {
    console.error(`tuning/exp.csv has ${r.totalExp.length - 1} rows; the level cap (data/balance.json) needs ${cap - 1}.`);
    process.exit(1);
  }
  writeTable('data/items.json', r.items);
  writeTable('data/monsters.json', r.monsters);
  writeFileSync('data/exp-table.json', `${JSON.stringify({ _comment: 'GENERATED by `npm run tuning` from tuning/exp.csv. totalExp[L-1] = total Exp to reach level L.', totalExp: r.totalExp }, null, 2)}\n`);
  updateStrings(r.names);
  for (const [id, map] of Object.entries(r.maps)) {
    if (JSON.stringify(map) !== JSON.stringify(maps[id])) {
      writeFileSync(`maps/${id}.json`, JSON.stringify(map));
      console.log(`updated spawns in maps/${id}.json`);
    }
  }
  writeFileSync('tuning/CATALOG.md', buildCatalog({
    items: r.items, monsters: r.monsters, totalExp: r.totalExp, strings: readJson('data/strings.zh-TW.json'),
    maps: r.maps, balance: readJson('data/balance.json'), shops: readJson('data/shops.json'), npcs: readJson('data/npcs.json'),
  }));
  console.log('Updated data/items.json, data/monsters.json, data/exp-table.json, strings and tuning/CATALOG.md.');
  console.log('Next: npm test (checks everything still fits together), then try it with npm run dev.');
} else {
  console.error(`Unknown command "${cmd}" (use: import, export, exp)`);
  process.exit(1);
}
